#!/usr/bin/env ruby
# frozen_string_literal: true

# Pulls TRMNL's own translations (usetrmnl/trmnl-i18n, MIT licence) at a pinned commit and writes the subset this
# plugin uses into plugin/src/shared.liquid between the I18N_TRMNL markers, so the texts can be re-synced.
#   ruby tools/sync_trmnl_i18n.rb [commit]      (needs `gh` logged in, or network access to raw.githubusercontent.com)
# Sources: locales/plugin_renders/<loc>.yml  renders.weather.{temperature,low,high,low_high_short,right_now,today,...}
#          renders.weather.weatherapi.conditions (code, day, night)   (TRMNL's native Weather plugin)
#          locales/custom_plugins/<loc>.yml   custom_plugins.{precipitation_probability,precipitation,wind,...}
require 'json'
require 'net/http'
require 'yaml'

COMMIT = ARGV[0] || 'd942836c695abd0849ed1430c657b6aa5cd9a3c0'
BASE = "https://raw.githubusercontent.com/usetrmnl/trmnl-i18n/#{COMMIT}/lib/trmnl/i18n/locales"
LOCALES = %w[cs da de-AT de en en-AU en-GB es-ES fr gu he hi hu id is it ja ko lt nl no pl pt-BR ro ru sk sl sv uk zh-CN zh-HK].freeze
WEATHER_KEYS = %w[temperature low_high_short today].freeze   # only what the plugin reads
PLUGIN_KEYS = %w[precipitation_probability precipitation wind].freeze
TEMPEST_KEYS = %w[snow].freeze   # renders.weather.tempest.conditions
# the WeatherAPI codes the Open-Meteo WMO codes map onto (see WMO_TO_WAPI in shared.liquid)
CODES = [1000, 1003, 1009, 1087, 1135, 1147, 1150, 1153, 1168, 1171, 1183, 1189, 1195, 1198, 1201, 1213, 1219, 1225, 1237,
         1246, 1264, 1276].freeze
NIGHT = [1000, 1003].freeze   # the only codes where TRMNL's night text differs (Sunny / Clear)

def fetch(path)
  res = Net::HTTP.get_response(URI("#{BASE}/#{path}"))
  res.is_a?(Net::HTTPSuccess) ? YAML.safe_load(res.body) : nil
end

SLOTS = WEATHER_KEYS.map { "w.#{_1}" } + PLUGIN_KEYS.map { "p.#{_1}" } + TEMPEST_KEYS.map { "t.#{_1}" } + CODES.map { "c#{_1}" } + NIGHT.map { "c#{_1}n" }
full = {}
LOCALES.each do |loc|
  entry = {}
  pr = fetch("plugin_renders/#{loc}.yml")&.dig(loc, 'renders', 'weather')
  if pr
    WEATHER_KEYS.each { |k| entry["w.#{k}"] = pr[k] if pr[k].is_a?(String) }
    TEMPEST_KEYS.each { |k| v = pr.dig('tempest', 'conditions', k); entry["t.#{k}"] = v if v.is_a?(String) }
    (pr.dig('weatherapi', 'conditions') || []).each do |c|
      next unless CODES.include?(c['code'])

      entry["c#{c['code']}"] = c['day']
      entry["c#{c['code']}n"] = c['night'] if c['night'] && c['night'] != c['day']
    end
  end
  cp = fetch("custom_plugins/#{loc}.yml")&.dig(loc, 'custom_plugins')
  PLUGIN_KEYS.each { |k| entry["p.#{k}"] = cp[k] if cp && cp[k].is_a?(String) } if cp
  full[loc] = entry
  warn "#{loc}: #{entry.size} texts"
end
# compact: each locale is one string of the texts in SLOTS order joined by "|"; a regional variant (de-AT, ...)
# keeps only the slots that differ from its base language, the others are empty
out = {}
full.each do |loc, entry|
  base = loc.include?('-') ? full[loc.split('-').first] : nil
  # TRMNL's English placeholder in another language counts as untranslated (the plugin then uses its own word), so
  # it is not stored either; nor what a regional variant shares with its base
  vals = SLOTS.map do |k|
    v = entry[k].to_s.tr('|', '/')
    (base && base[k] == entry[k]) || (!loc.start_with?('en') && v == full['en'][k].to_s) ? '' : v
  end
  out[loc] = vals.join('|').sub(/\|+\z/, '')
end
block = "// ==== I18N_TRMNL_BEGIN ==== generated by tools/sync_trmnl_i18n.rb from usetrmnl/trmnl-i18n@#{COMMIT[0, 7]} (MIT); do not edit\n" \
        "var I18N_SLOTS = #{JSON.generate(SLOTS)};\nvar I18N_TRMNL = #{JSON.generate(out)};\n// ==== I18N_TRMNL_END ===="
path = File.expand_path('../plugin/src/shared.liquid', __dir__)
src = File.read(path)
a = src.index('// ==== I18N_TRMNL_BEGIN ====')
b = src.index('// ==== I18N_TRMNL_END ====')
raise 'I18N_TRMNL markers missing in shared.liquid' unless a && b

File.write(path, src[0...a] + block + src[(b + '// ==== I18N_TRMNL_END ===='.length)..])
puts "wrote #{out.size} locales, #{block.bytesize} bytes"
